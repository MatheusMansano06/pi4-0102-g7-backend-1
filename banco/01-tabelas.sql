CREATE TABLE materiais (
    material_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    descricao VARCHAR(255),
    especificacao VARCHAR(255),
    quantidade_disponivel INTEGER NOT NULL,
    quantidade_minima INTEGER NOT NULL,
    ativo BOOLEAN NOT NULL,
    atualizada_em TIMESTAMP WITHOUT TIME ZONE,
    -- Regra do MVP confirmada pelo Luis no #1136: ambas permitidas e opcionais.
    -- NULL explicito continua representando configuracao incompleta, recusada pela API.
    aceita_dimensao BOOLEAN DEFAULT TRUE,
    exige_dimensao BOOLEAN DEFAULT FALSE,
    aceita_diametro BOOLEAN DEFAULT TRUE,
    exige_diametro BOOLEAN DEFAULT FALSE
);

CREATE TABLE solicitacoes (
    solicitacao_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    material_id BIGINT,
    quantidade INTEGER NOT NULL,
    status VARCHAR(255),
    criada_em TIMESTAMP,
    atualizada_em TIMESTAMP,
    previsao_retirada TIMESTAMP,
    observacao VARCHAR(255),
    dimensao VARCHAR(255),
    diametro DOUBLE PRECISION,

    FOREIGN KEY (material_id)
        REFERENCES materiais(material_id)
);
