
-- TABELA: USUARIOS

CREATE TABLE usuarios (
    usuario_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    -- Dados específicos de cada perfil
    ra VARCHAR(30),
    curso VARCHAR(120),
    matricula_funcional VARCHAR(30),
    cargo VARCHAR(100),

    CONSTRAINT ck_usuarios_perfil
        CHECK (perfil IN ('ALUNO', 'RESPONSAVEL')),

    CONSTRAINT ck_usuarios_dados_perfil
        CHECK (
            (
                perfil = 'ALUNO'
                AND ra IS NOT NULL AND TRIM(ra) <> ''
                AND curso IS NOT NULL AND TRIM(curso) <> ''
                AND matricula_funcional IS NULL
                AND cargo IS NULL
            )
            OR
            (
                perfil = 'RESPONSAVEL'
                AND matricula_funcional IS NOT NULL
                AND TRIM(matricula_funcional) <> ''
                AND cargo IS NOT NULL AND TRIM(cargo) <> ''
                AND ra IS NULL
                AND curso IS NULL
            )
        )
);

CREATE UNIQUE INDEX uq_usuarios_email
    ON usuarios (LOWER(email));

CREATE UNIQUE INDEX uq_usuarios_ra
    ON usuarios (ra)
    WHERE ra IS NOT NULL;

CREATE UNIQUE INDEX uq_usuarios_matricula
    ON usuarios (matricula_funcional)
    WHERE matricula_funcional IS NOT NULL;

-- TABELA: MATERIAIS

CREATE TABLE materiais (
    material_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    descricao VARCHAR(255),
    especificacao VARCHAR(255),
    quantidade_disponivel INTEGER NOT NULL,
    quantidade_minima INTEGER NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    atualizada_em TIMESTAMP WITHOUT TIME ZONE,

    -- Regras para dimensão e diâmetro
    aceita_dimensao BOOLEAN DEFAULT TRUE,
    exige_dimensao BOOLEAN DEFAULT FALSE,
    aceita_diametro BOOLEAN DEFAULT TRUE,
    exige_diametro BOOLEAN DEFAULT FALSE,

    CONSTRAINT ck_materiais_quantidade
        CHECK (quantidade_disponivel >= 0),

    CONSTRAINT ck_materiais_quantidade_minima
        CHECK (quantidade_minima >= 0),

    CONSTRAINT ck_materiais_dimensao
        CHECK (exige_dimensao IS NOT TRUE OR aceita_dimensao IS TRUE),

    CONSTRAINT ck_materiais_diametro
        CHECK (exige_diametro IS NOT TRUE OR aceita_diametro IS TRUE)
);

-- TABELA: SOLICITACOES

CREATE TABLE solicitacoes (
    solicitacao_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    material_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    status VARCHAR(255),
    criada_em TIMESTAMP WITHOUT TIME ZONE,
    atualizada_em TIMESTAMP WITHOUT TIME ZONE,
    previsao_retirada TIMESTAMP WITHOUT TIME ZONE,
    observacao VARCHAR(255),
    dimensao VARCHAR(255),
    diametro DOUBLE PRECISION,

    CONSTRAINT fk_solicitacoes_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(usuario_id),

    CONSTRAINT fk_solicitacoes_material
        FOREIGN KEY (material_id)
        REFERENCES materiais(material_id),

    CONSTRAINT ck_solicitacoes_quantidade
        CHECK (quantidade > 0),

    CONSTRAINT ck_solicitacoes_diametro
        CHECK (diametro IS NULL OR diametro > 0)
);


-- INDICES PARA CONSULTAS

CREATE INDEX idx_solicitacoes_usuario
    ON solicitacoes(usuario_id);

CREATE INDEX idx_solicitacoes_material
    ON solicitacoes(material_id);

CREATE INDEX idx_solicitacoes_status
    ON solicitacoes(status);

CREATE INDEX idx_materiais_nome
    ON materiais(nome);
